"""第005回 諫早 伊木力 のショット定義。

時刻は秒で直書きせず、台詞番号から引く（T=行の頭, TE=行の尻）。
音声の頭には LEAD_IN 0.4 秒、尻には TAIL 0.9 秒の余白がある。各話の最初のショットは
0 秒から始め、最後のショットは TE(最終行, 0.9) で終わらせて音声の全長とそろえる。

テーマは「史跡」。石碑（町を横に振る）でも土木（1点に寄る）でも地形（レイヤを
差し替える）でもない4つ目の型で、**地面の下にあるものを、地上の画で示せない**。
だから画は「地上のいまの姿」と「発掘の記録（札と数字）」の二層になる。
カメラはずっと同じ斜面を見ていて、動くのは注記のほうである。

**この土地でいちばん効いたのは傾斜量図だった。**README には「人工の段差が
無いところでは何も出ない」と書いてあるが、ここは段だらけ（みかんの段々畑）なので
逆に段が面で出る。谷を横切るダムの堤体も黒い一本の線で出る。

**ただし slopemap のズーム上限は 15。**16 を指定すると Master が 15 から
2倍に引き伸ばすのでぼやける。傾斜量図のショットは z14〜15 で組むこと。

**明治期の低湿地 `swale` はこの回では使えない。**斜面ばかりの土地なので、
実測で墓所 14% / ダム 3% しか塗られていない（伊木力川の河口だけ 55%）。
第004回の型はそのまま持ち込めなかった。

**ズームは地上の広さから決める。**緯度32.8度、画面 1920px で入る横幅:

    z12 62km / z13 31km / z14 15km / z15 7.7km / z16 3.8km / z17 1.9km

収めたいものは 伊木力〜千々石 25.3km、伊木力の谷 約2km、墓所まわり 約400m。
最初の1本だけが広く、あとはずっと同じ谷にいる。
"""

