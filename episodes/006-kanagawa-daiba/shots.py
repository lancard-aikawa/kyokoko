    pale = {"id": "pale"}
    hill = lambda k: {"id": "hillshademap", "alpha": k}       # noqa: E731
    swale = lambda k: {"id": "swale", "alpha": k}             # noqa: E731
    usa = lambda k=None: ({"id": "ort_USA10"} if k is None    # noqa: E731
                          else {"id": "ort_USA10", "alpha": k})
